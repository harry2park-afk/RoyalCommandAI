import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL("..", import.meta.url)));
const output = join(root, "src/config/generated/packRegistry.generated.ts");

function jsonFiles(directory, kind) {
  return readdirSync(join(root, directory), { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => {
      const path = join(root, directory, entry.name);
      const data = JSON.parse(readFileSync(path, "utf8"));
      if (typeof data.packId !== "string" || !data.packId.startsWith(`${kind}-`)) throw new Error(`${entry.name}: invalid packId`);
      if (!["READY", "NEEDS_REVIEW", "BLOCKED"].includes(data.status)) throw new Error(`${entry.name}: explicit pack status is required`);
      return {
        name: basename(entry.name, ".json"), data,
        importPath: `../${relative(join(root, "src/config"), path).replaceAll("\\", "/")}`,
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

const countries = jsonFiles("src/config/countries", "country");
const regions = jsonFiles("src/config/regions", "region");
const policies = jsonFiles("src/config/policies", "policy");
for (const [kind, files] of [["country", countries], ["region", regions], ["policy", policies]]) {
  const ids = files.map((file) => file.data.packId);
  if (new Set(ids).size !== ids.length) throw new Error(`Duplicate ${kind} packId`);
}

const countryIds = new Set(countries.map((file) => file.data.packId));
const regionIds = new Set(regions.map((file) => file.data.packId));
const policyIds = new Set(policies.map((file) => file.data.packId));
const domainInventory = JSON.parse(readFileSync(join(root, "src/config/domainAssets.json"), "utf8"));
const domains = domainInventory.assets.map((asset) => asset.domain);
if (new Set(domains).size !== domains.length) throw new Error("Duplicate domain asset");
for (const asset of domainInventory.assets.filter((item) => item.runtimeEnabled)) {
  if (!asset.runtimeBinding) throw new Error(`${asset.domain}: runtimeBinding is required`);
  if (!asset.activationChecks || !Object.values(asset.activationChecks).every(Boolean)) throw new Error(`${asset.domain}: activation checks are incomplete`);
  if (!regionIds.has(`region-${asset.regionCode.toLowerCase()}`)) throw new Error(`${asset.domain}: Region Pack is not READY`);
  if (!policyIds.has(asset.policyPackId)) throw new Error(`${asset.domain}: Policy Pack is not READY`);
  if (asset.runtimeBinding !== "GLOBAL" && !countryIds.has(asset.countryPackId)) throw new Error(`${asset.domain}: Country Pack is not READY`);
}
const imports = [];

for (const [prefix, files] of [["country", countries], ["region", regions], ["policy", policies]]) {
  files.forEach((file, index) => imports.push(`import ${prefix}${index} from "${file.importPath}";`));
}

const countryRows = countries.map((_file, index) => `  [country${index}.packId, country${index} as CountryPack],`);
const regionRows = regions.map((_file, index) => `  [region${index}.packId, region${index} as RegionPack],`);
const policyRows = policies.map((_file, index) => `  [policy${index}.packId, policy${index} as PolicyPack],`);

const source = `/* Generated by scripts/generate-domain-pack-registry.mjs. Do not edit. */
import type { CountryPack, PolicyPack, RegionPack } from "../packs/types";
${imports.join("\n")}

export const GENERATED_COUNTRY_PACKS = new Map<string, CountryPack>([
${countryRows.join("\n")}
]);

export const GENERATED_REGION_PACKS = new Map<string, RegionPack>([
${regionRows.join("\n")}
]);

export const GENERATED_POLICY_PACKS = new Map<string, PolicyPack>([
${policyRows.join("\n")}
]);
`;

mkdirSync(join(root, "src/config/generated"), { recursive: true });
writeFileSync(output, source, "utf8");
